function updateSkillStatus() {
  const count = document.querySelectorAll('.skill-cloud button.is-selected').length;
  const key = count ? 'skillSelected' : 'skillHint';
  document.querySelector('[data-skill-status]').textContent = translations[currentLanguage][key].replace('{count}', count);
}

function fillProjectDialog(projectKey) {
  const project = projectDetails[currentLanguage][projectKey];
  if (!project) return;
  projectDialog.querySelector('.dialog-type').textContent = project.type;
  projectDialog.querySelector('#dialog-title').textContent = project.title;
  projectDialog.querySelector('.dialog-summary').textContent = project.summary;
  projectDialog.querySelector('.dialog-role').textContent = project.role;
  projectDialog.querySelector('.dialog-outcome').textContent = project.outcome;
  projectDialog.querySelector('.dialog-tools').textContent = project.tools;
}

function setLanguage(language) {
  const lang = translations[language] ? language : 'zh';
  const copy = translations[lang];
  currentLanguage = lang;
  root.lang = lang === 'zh' ? 'zh-CN' : 'en';
  document.title = copy.title;
  document.querySelector('meta[name="description"]').content = copy.description;
  document.querySelector('meta[property="og:title"]').content = copy.title;
  document.querySelector('meta[property="og:description"]').content = copy.description;

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const value = copy[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    const value = copy[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });
  languageButtons.forEach(button => {
    const selected = button.dataset.lang === lang;
    button.classList.toggle('is-active', selected);
    button.setAttribute('aria-pressed', String(selected));
  });
  document.querySelector('[data-current-label]').textContent = copy[panelMeta[currentPanel].label];
  updateSkillStatus();
  if (activeProject) fillProjectDialog(activeProject);
  localStorage.setItem('resume-language', lang);
}

function setTheme(theme) {
  root.classList.toggle('dark', theme === 'dark');
  document.querySelector('meta[name="theme-color"]').content = theme === 'dark' ? '#09111b' : '#e8edf3';
  localStorage.setItem('resume-theme', theme);
}

function activatePanel(name, updateHistory = true) {
  if (!panelMeta[name]) name = 'about';
  currentPanel = name;
  navTabs.forEach(tab => {
    const selected = tab.dataset.tab === name;
    tab.classList.toggle('is-active', selected);
    tab.setAttribute('aria-selected', String(selected));
    tab.tabIndex = selected ? 0 : -1;
  });
  panels.forEach(panel => {
    const selected = panel.dataset.panel === name;
    panel.hidden = !selected;
    panel.classList.toggle('is-active', selected);
    if (selected) {
      panel.classList.remove('is-entering');
      void panel.offsetWidth;
      panel.classList.add('is-entering');
      panel.scrollTop = 0;
    }
  });
  document.querySelector('[data-current-index]').textContent = panelMeta[name].index;
  document.querySelector('[data-current-label]').textContent = translations[currentLanguage][panelMeta[name].label];
  if (updateHistory && location.hash !== `#${name}`) history.pushState({ panel:name }, '', `#${name}`);
}

