function animateCounter(element) {
  const target = Number(element.dataset.count);
  const suffix = element.dataset.suffix || '';
  if (element.dataset.counted || reducedMotion.matches) {
    element.textContent = `${target}${suffix}`;
    return;
  }
  element.dataset.counted = 'true';
  const started = performance.now();
  const tick = now => {
    const progress = Math.min((now - started) / 750, 1);
    element.textContent = `${Math.round(target * (1 - Math.pow(1 - progress, 3)))}${suffix}`;
    if (progress < 1) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}
document.querySelectorAll('[data-count]').forEach(animateCounter);

function bindCardMotion(card) {
  if (card.dataset.motionBound) return;
  card.dataset.motionBound = 'true';
  let frame = 0;
  card.addEventListener('pointermove', event => {
    if (!finePointer.matches || reducedMotion.matches) return;
    const rect = card.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width;
    const y = (event.clientY - rect.top) / rect.height;
    cancelAnimationFrame(frame);
    frame = requestAnimationFrame(() => {
      card.style.setProperty('--px', `${x * 100}%`);
      card.style.setProperty('--py', `${y * 100}%`);
      card.style.setProperty('--rx', `${(.5 - y) * 2.2}deg`);
      card.style.setProperty('--ry', `${(x - .5) * 2.2}deg`);
      const visual = card.querySelector('.mini-ui, .statement-visual, .compact-mark');
      if (visual) visual.style.translate = `${(x - .5) * 7}px ${(y - .5) * 7}px`;
    });
  });
  card.addEventListener('pointerleave', () => {
    card.style.setProperty('--rx', '0deg');
    card.style.setProperty('--ry', '0deg');
    const visual = card.querySelector('.mini-ui, .statement-visual, .compact-mark');
    if (visual) visual.style.translate = '0 0';
  });
}
